import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const compile=p=>ts.transpileModule(fs.readFileSync(p,'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const url=s=>'data:text/javascript;base64,'+Buffer.from(s).toString('base64');
const tourUrl=url(compile('lib/tour.ts'));
const t=await import(tourUrl);
const f=await import(url(compile('lib/filters.ts').replace("'./tour'",JSON.stringify(tourUrl))));
const past={start:'2020-01-01',end:'2020-01-05',price:1000,seats:20};
const future={start:'2099-11-01',end:'2099-11-05',price:20000,seats:0};
const tour={id:'test',category:'ทัวร์',country:'ญี่ปุ่น',price:1000,activityTags:['แสงเหนือ'],departures:[past,future]};
assert.equal(t.tourClosed(tour),false,'a future sold-out round does not archive a tour');
assert.equal(t.tourClosed({...tour,departures:[past]}),true);
assert.equal(t.tourClosed({...tour,departures:[]}),false,'undated tours remain available for inquiry');
assert.equal(t.departureExpired({start:'2026-10-04'},'2026-10-04'),false,'departure day stays open');
assert.equal(t.departureExpired({start:'2026-10-03'},'2026-10-04'),true);
assert.equal(t.businessDate(new Date('2026-10-03T20:00:00Z')),'2026-10-04');
assert.equal(t.startingPrice(tour),20000,'expired cheap rounds do not affect public starting price');
assert.equal(f.matchesFilters(tour,{...f.emptyFilters,max:'2000'}),false);
assert.equal(f.matchesFilters(tour,{...f.emptyFilters,from:'2099-11-01',to:'2099-11-05',max:'20000',tags:['แสงเหนือ']}),true);
assert.equal(f.matchesFilters(tour,{...f.emptyFilters,from:'2099-11-01',to:'2099-11-04'}),false);
assert.equal(f.matchesFilters(tour,{...f.emptyFilters,from:'2099-11-01',max:'2000'},true),false,'date and price must match the same departure');
assert.equal(f.matchesFilters(tour,{...f.emptyFilters,tags:['ช้อปปิ้ง']}),false);
assert.equal(f.matchesFilters(tour,{...f.emptyFilters,country:'ออสเตรีย'}),false);
assert.equal(f.matchesFilters(tour,{...f.emptyFilters,min:'20000',max:'1000'}),false);
assert.equal(t.validDate('2026-02-30'),false);
assert.equal(t.validDate('2028-02-29'),true);
assert.equal(t.tourClosed({...tour,departures:[past,{...future,start:'2099-12-01'}]}),false,'adding a future round reopens a closed tour');
console.log('17 catalog, date-boundary, closure and filter assertions passed');
